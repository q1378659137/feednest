  const DICTS = { 'zh-TW': TW, en: EN };
  let current = 'zh-CN';

  function t(text, vars) {
    const table = DICTS[current];
    let out = (table && table[text]) || text;
    if (vars) {
      out = out.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
    }
    return out;
  }

  function setLang(code) {
    current = code === 'zh-CN' || DICTS[code] ? code : 'zh-CN';
    document.documentElement.lang = current === 'en' ? 'en' : current === 'zh-TW' ? 'zh-Hant' : 'zh-CN';
    return current;
  }

  function getLang() {
    return current;
  }

  /** 翻译带 data-i18n / data-i18n-ph / data-i18n-title 的静态元素 */
  function applyStatic(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    scope.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPh);
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.title = t(el.dataset.i18nTitle);
    });
  }

  window.I18N = { LANGS, t, setLang, getLang, applyStatic, dicts: DICTS };
  window.t = t;
